pub fn generate_traits(count: usize) -> Vec<Traits> {
    let mut traits = vec![];
    let mut banned_traits = HashSet::new();

    let mut all_traits = Traits::get_list();
    all_traits.shuffle(&mut rand::rng());

    while traits.len() < count {
        let Some(ch_trait) = all_traits.pop() else {
            break;
        };

        let negatives = ch_trait.get_negative();

        if negatives.iter().any(|neg| banned_traits.contains(neg)) {
            continue;
        }

        traits.push(ch_trait);
        for neg in negatives {
            banned_traits.insert(neg);
        }
    }

    traits
}